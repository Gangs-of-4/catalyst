// Vercel build (ADR-0036, ADR-0042). Produces dist/ with:
//   - the React app (frontend/app, built by Vite): its shell as dist/app.html, its files in dist/assets/
//   - the old static pages and static/, unchanged, until M8 replaces each one
// vercel.json rewrites each React route (e.g. /styleguide) to /app: with cleanUrls on, Vercel serves
// dist/app.html at /app, and a rewrite to /app.html would 404.
// Runs with plain Node; installs the app's locked dependencies if they aren't there yet.
import { execSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";

const raw = (process.env.NEXT_PUBLIC_API_URL || "").trim().replace(/\/+$/, "");
if (raw && !/^https:\/\/[^\s/]+(\/[^\s]*)?$/.test(raw)) {
  console.error("NEXT_PUBLIC_API_URL must be empty or an https:// URL.");
  process.exit(1);
}

// Tell the app whether this deploy has a backend behind /api (NEXT_PUBLIC_API_URL set, ADR-0041).
// Without one, the "waking up" gate says so at once instead of waiting 90 s for a /healthz that
// can never answer (review on #26). Local dev doesn't use build.mjs, so it always waits for a backend.
const run = (cmd) =>
  execSync(cmd, { cwd: "app", stdio: "inherit", env: { ...process.env, VITE_BACKEND_CONFIGURED: raw ? "1" : "0" } });

// 1. The React app.
if (!existsSync("app/node_modules")) run("npm ci --no-audit --no-fund");
run("npm run build");

rmSync("dist", { recursive: true, force: true });
mkdirSync("dist");
// Everything Vite built; its index.html becomes app.html, which every React route (including "/") rewrites to.
cpSync("app/dist", "dist", { recursive: true, filter: (src) => !/[\\/]app[\\/]dist[\\/]index\.html$/.test(src) });
cpSync("app/dist/index.html", "dist/app.html");

// 2. The old static pages (removed page by page during M8).
// The old static try page (index.html) and desk (desk.html) are no longer shipped: "/", /demo/clinic
// and /desk are React pages. setup.html stays until M8 replaces it.
for (const page of ["setup.html"]) cpSync(page, `dist/${page}`);
cpSync("static", "dist/static", { recursive: true });
// The old pages call /api on their own origin too: Vercel rewrites it to the backend (ADR-0041,
// configure-vercel.mjs), so they no longer need the backend URL or CORS.
writeFileSync("dist/static/config.js",
  `// Generated by build.mjs. Empty = call /api on this origin (Vercel rewrites it, ADR-0041).
window.CATALYST_API_URL = "";
`);
console.log(raw ? "Pages call /api on this origin; Vercel rewrites it to the backend." : "NEXT_PUBLIC_API_URL is empty: no backend to reach.");
